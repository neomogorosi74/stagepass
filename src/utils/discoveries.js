export function getDiscoveryForVisit(visitNumber) {
  return DISCOVERIES.find(d => d.visitNumber === visitNumber) || null
}

export function getDiscoveryById(id) {
  return DISCOVERIES.find(d => d.id === id) || null
}

export function getDiscoveryCountForRegion(region) {
  return DISCOVERIES.filter(d => d.region === region).length
}

export function getTotalDiscoveryCount() {
  return DISCOVERIES.length
}

export function getRegionCompletion(members) {
  const unlockedCounts = {}
  for (const r of REGIONS) {
    unlockedCounts[r.id] = 0
  }
  let totalUnlocked = 0
  for (const m of members) {
    const discos = m.discoveries || []
    totalUnlocked += discos.length
    for (const dId of discos) {
      const d = getDiscoveryById(dId)
      if (d) unlockedCounts[d.region]++
    }
  }
  const totalPossible = members.length * Object.keys(unlockedCounts).length || 1
  return {
    totalUnlocked,
    byRegion: unlockedCounts,
    completionPct: Math.round((totalUnlocked / totalPossible) * 100),
  }
}

export function getRecentDiscoveries(members, limit = 20) {
  const entries = []
  for (const m of members) {
    const discos = m.discoveries || []
    for (const dId of discos) {
      const d = getDiscoveryById(dId)
      if (d) {
        entries.push({
          memberName: m.firstName,
          memberPhone: m.phoneNumber,
          discoveryId: d.id,
          content: d.content,
          tag: d.tag,
          region: d.region,
          visitNumber: d.visitNumber,
          timestamp: m.lastVisitAt,
        })
      }
    }
  }
  entries.sort((a, b) => new Date(b.timestamp) - new Date(a.timestamp))
  return entries.slice(0, limit)
}
